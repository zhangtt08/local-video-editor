import assert from "node:assert/strict";
import { copyClips, pasteCommands, relatedClips, selectionQuantum, type ClipClipboard } from "../desktop/src/selection";
import { type Project, type Clip, type Track } from "../desktop/src/engine";
import { TIMEBASE as T } from "../desktop/src/time";
import { originPort } from "../desktop/src/bridge";
import { editableProject, get } from "../desktop/src/store";

assert.equal(originPort("http://127.0.0.1:9853"), 9853);
assert.equal(originPort("http://127.0.0.1"), 80);
assert.equal(originPort("https://example.com"), 443);
assert.equal(originPort("invalid"), 0);

const p: Project = { schema_version: 4, id: "source", revision: 1, name: "source", notes: "", settings: { timebase: T, width: 1280, height: 720, frame_rate: { numerator: 30, denominator: 1 }, sample_rate: 48000 }, assets: { a: { id: "a", kind: "image", label: "a", reference: "metadata", duration_ticks: null, verified: null }, sound: { id: "sound", kind: "audio", label: "sound", reference: "metadata", duration_ticks: 10*T, verified: null } }, tracks: [{ id: "v", kind: "video", name: "Video", locked: true, muted: false, hidden: false, volume: 1 }, { id: "s", kind: "audio", name: "Sound", muted: false, hidden: false, volume: .7 }], clips: { left: { id: "left", asset_id: "a", track_id: "v", position_ticks: T, source_in_ticks: 0, duration_ticks: 2*T, keyframes: [{ property: "x", at_ticks: T, value: .25, interpolation: "ease" }], animation_offset_ticks: T/2 }, right: { id: "right", asset_id: "a", track_id: "v", position_ticks: 2*T, source_in_ticks: 0, duration_ticks: 2*T, transition_in: { from_clip_id: "left", kind: "dissolve", duration_ticks: T } }, music: { id: "music", asset_id: "sound", track_id: "s", position_ticks: T, source_in_ticks: 2*T, duration_ticks: 3*T } } };
p.tracks[0].blend_mode = "screen";
const candidate = { ...p, revision: 2 };
const batchState = { ...get(), project: p, mode: "batch" as const, batch: [{ op: "clip.patch", clip_id: "left", effects: { x: .2 } }], candidate };
assert.equal(editableProject(batchState), candidate);
assert.equal(editableProject({ ...batchState, dryRunBusy: true }), null);
assert.equal(editableProject({ ...batchState, dryRunBusy: true }, true), candidate);
assert.equal(editableProject({ ...batchState, dryRunError: "invalid" }), null);
assert.equal(editableProject({ ...batchState, candidate: { ...candidate, revision: 3 } }), null);
assert.equal(editableProject({ ...batchState, candidate: { ...candidate, id: "other" } }), null);
assert.equal(editableProject({ ...batchState, batch: [] }), p);
assert.equal(editableProject({ ...batchState, mode: "instant" }), p);
const copied = copyClips(p, ["left", "right", "music"]);
p.clips.left.keyframes![0].value = 99;
assert.equal(copied.clips[0].keyframes![0].value, .25);
const plan = pasteCommands(p, copied, 8*T);
assert.equal(plan.commands.length, 1);
const pasted = plan.commands[0].clips as Clip[];
assert.equal(pasted[0].position_ticks, 8*T);
assert.equal(pasted[1].position_ticks, 9*T);
assert.equal(pasted[1].transition_in!.from_clip_id, pasted[0].id);
assert.equal(pasted[2].source_in_ticks, 2*T);
assert.equal(pasted[0].animation_offset_ticks, T/2);
assert.notEqual(pasted[0].id, "left");
assert.equal((pasteCommands(p, copyClips(p, ["right"]), 8*T).commands[0].clips as Clip[])[0].transition_in, null);
const other = { ...p, id: "other", assets: {}, tracks: [], clips: {} };
const across = pasteCommands(other, copied, 0);
assert.equal(across.commands.filter(c=>c.op==="asset.register").length, 2);
const tracks = across.commands.filter(c=>c.op==="track.add").map(c=>c.track as Track);
assert.equal(tracks.length, 2); assert(tracks.every(t=>!t.locked)); assert.equal(tracks[1].volume, .7);
assert.equal(tracks[0].blend_mode, "screen");
assert.equal(copied.tracks[0].locked, true);
assert.equal(selectionQuantum(p, ["left", "music"]), T/30);
const fractional = { ...p, settings: { ...p.settings, frame_rate: { numerator: 30000, denominator: 1001 }, sample_rate: 44100 } };
const q = selectionQuantum(fractional, ["left", "music"]);
assert.equal(q % (T*1001/30000), 0); assert.equal(q % (T/44100), 0);
const verifiedCopy = structuredClone(copied) as ClipClipboard;
verifiedCopy.assets[0].verified = { ...verifiedCopy.assets[0], probe_id: "trusted", content_sha256: "hash" } as never;
const imported = pasteCommands(other, verifiedCopy, 0);
assert.equal(imported.commands[0].op, "asset.import"); assert.equal(imported.commands[0].probe_id, "trusted");
assert.equal(copied.clips[1].transition_in!.from_clip_id, "left");
const earlier = pasteCommands(other, copied, 0).commands.at(-1)!.clips as Clip[];
assert.equal(earlier[0].position_ticks, 0);
assert.equal(earlier[1].position_ticks, T);
const staggered = copyClips(p, ["left", "music"]);
staggered.clips[1].position_ticks = T - T / 48000;
const aligned = pasteCommands(other, staggered, 5*T).commands.at(-1)!.clips as Clip[];
assert.equal(aligned[0].position_ticks % (T/30), 0);
assert.equal(aligned[1].position_ticks % (T/48000), 0);
assert.equal(aligned[0].position_ticks - aligned[1].position_ticks, T/48000);
const changed = { ...p, assets: { ...p.assets, a: { ...p.assets.a, reference: "replaced" } } };
assert.equal(pasteCommands(changed, copied, 8*T).commands[0].op, "asset.register");
const linked = structuredClone(p);
linked.clips.left.group_id = "group"; linked.clips.right.group_id = "group";
linked.clips.right.link_id = "pair"; linked.clips.music.link_id = "pair"; linked.clips.music.link_source_offset_ticks = T;
assert.deepEqual(relatedClips(linked, ["left"]), ["left", "right", "music"]);
assert.deepEqual(relatedClips(linked, ["right"], true), ["right", "music"]);
assert.equal(copyClips(linked, ["right"]).clips[0].link_id, null);
const linkedCopy = copyClips(linked, ["left", "right", "music"]);
const linkedPaste = pasteCommands(linked, linkedCopy, 8*T).commands[0].clips as Clip[];
assert.notEqual(linkedPaste[0].group_id, "group"); assert.equal(linkedPaste[0].group_id, linkedPaste[1].group_id);
assert.notEqual(linkedPaste[1].link_id, "pair"); assert.equal(linkedPaste[1].link_id, linkedPaste[2].link_id); assert.equal(linkedPaste[2].link_source_offset_ticks, T);
console.log("PASS: clipboard clocks, transitions, tracks, persistent group/link closure and isolated copies");
